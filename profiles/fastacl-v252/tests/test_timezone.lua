local tz=require('fastacl252_timezone')
local name,zone=tz.resolve('US','美国 洛杉矶 10G')
assert(name=='America/Los_Angeles')
assert(zone.posix=='PST8PDT,M3.2.0,M11.1.0')
name,zone=tz.resolve('US','美国 纽约')
assert(name=='America/New_York')
name,zone=tz.resolve('JP','Tokyo')
assert(name=='Asia/Tokyo')
name,zone=tz.resolve('','香港 HK')
assert(name=='Asia/Hong_Kong')
name,zone=tz.resolve('DE','')
assert(name=='Europe/Berlin')
assert(tz.get('America/Chicago').label=='美国中部时间')
print('PASS proxy country and city timezone mapping')
